//! The reference mean for `nomic-embed-text`, and why it is a constant rather than a computation.
//!
//! Transformer embeddings crowd into a narrow cone, so unrelated sentences sit at cosine ~0.43
//! rather than ~0. Subtracting the shared direction removes it, and the hyperplanes stop spending
//! themselves on a component every vector has in common.
//!
//! **The mean is a property of the model, not of the corpus, and that was tested rather than
//! assumed.** Two disjoint corpora of 48 sentences each - different topics, different register, no
//! overlap - produce means with `cos = 0.939` between them. Centring corpus B by corpus *A's* mean
//! takes B's unrelated-pair cosine from 0.420 to 0.048, essentially as well as its own mean does
//! (-0.045). See `nutcracker-crypto/examples/real_embeddings.rs`.
//!
//! That is what makes this a constant. If the mean had been corpus-specific, every namespace would
//! have needed its own, computed once and frozen, and every growing corpus would have faced a
//! migration to a better estimate. Instead an index is stable from its first item.
//!
//! For scale: the mean of 96 unit vectors drawn uniformly on a 768-sphere would have norm ~0.10.
//! This one has norm **0.659**. That number is the cone.
//!
//! **Revising this constant is a migration.** Different mean, different tokens, and every memory
//! stored under the old one becomes unfindable. So it is versioned into the embedder identity
//! (`+centred-v1`) and the existing manifest check refuses to run against a changed one. There is
//! no separate machinery for it because it needs none.
//!
//! Estimated from 96 sentences over 24 topics on 2026-08-30. A larger sample would give a better
//! estimate and would also be a migration, which is the reason not to keep fiddling with it.

